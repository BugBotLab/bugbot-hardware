# BugBot Kit board schematic, generated (spec: docs/kit-spec.md).  Writes only BugBot_Kit_Board.kicad_sch.
#   "C:/Program Files/KiCad/10.0/bin/python.exe" design/schematics/Kit/make_kit_schematic.py
#
# One daughter board for a Seeed XIAO ESP32-S3 Sense.  The XIAO is the whole brain; this board carries the
# four vibration motors and their drivers, a 9-axis IMU, a header for a bought distance-sensor module, the
# WS2812 lamp, the cell and the master switch.
#
#   cell (1S LiPo, J1) -> SW1 master switch -> Q1 reverse-polarity P-FET -> VMOT
#   VMOT feeds the motor driver and, through J2, the XIAO's BAT+/BAT- solder pads, so the XIAO's own
#   SGM40567 charger (110 mA) charges the cell over its USB-C.  3V3 comes back from the XIAO (SGM6029
#   DC-DC, 600 mA shared with the ESP32-S3), so budget ~300 mA for everything on this board.
#
# One DRV8833 drives all four motors, chosen 2026-11-24 over four I2C DRV8830s: $1.08 against $5.90 at 100 off,
# and 36,630 in stock against 948 (the DRV8830 had a 237-board ceiling).  It costs four GPIOs, which uses up
# every free pad on the XIAO, and it costs the per-motor current limit and the fault line.
#
#   HOW FOUR MOTORS COME OUT OF TWO H-BRIDGES.  Each motor goes between one output and VMOT, not GND, so it
#   runs when its output is pulled LOW.  From the DRV8833 truth table (00 = both Z, 01 = L H, 10 = H L,
#   11 = L L), xOUT1 is low exactly when xIN2 is high and xOUT2 is low exactly when xIN1 is high.  So each
#   half-bridge is independent, but the control is CROSSED:
#       motor A on AOUT1 <- AIN1 pad D0?  NO: motor A is driven by AIN2.   Mapping, for firmware:
#       AIN2 (D1) -> motor A      AIN1 (D0) -> motor B      BIN2 (D7) -> motor C      BIN1 (D6) -> motor D
#   THE CATCH, and it is a real one: the two motors on one bridge share a decay mode.  While motor A is PWMed
#   off, the bridge sits at 00 (coast, fast decay) if motor B is off, but at 10 (both ends at VMOT, slow decay)
#   if motor B is on.  So motor A's average current for a given duty depends on whether motor B is running.
#   Firmware must either calibrate that out or drive the pair in a fixed pattern.  The DRV8830s did not do this.
#
# Reused unchanged from the three-board stack, because it is drawn, ERC-clean and SPICE-checked there:
#   - the BNO055 circuit (crystal, CAP, RESET and BOOT pull-ups), from design/schematics/Odometry/03_imu.kicad_sch
#
# NOT yet settled (see docs/kit-spec.md, Open items).  These are placeholders, deliberately visible:
#   - the motor terminations J5..J8 are 1x02 2.54 headers until the motors are bought and measured
#   - AISEN and BISEN are tied to GND, so there is no current limit at all.  If the chosen motors need one,
#     fit sense resistors there - but the limit is then shared by the two motors on that bridge.
