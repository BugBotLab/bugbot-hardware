# 15.24 mm apart.  Two 1x07 sockets rather than a 2x07 part, because no stock 2x07 footprint has 0.6 in rows.
# They must be placed 15.24 mm apart and the XIAO must stand clear of the board: its Sense expansion board
# hangs ~6 mm below the pad plane, so use full-height sockets, not low-profile ones.
# Every free pad is now used.  Two placements are forced, not chosen:
#   VBAT_SENSE must land on an ADC pin, and only D0-D5 (GPIO1-6) have one - D6/D7 are GPIO43/44, which have
