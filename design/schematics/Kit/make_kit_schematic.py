# ---------------------------------------------------------------- the JLC BOM, as the other boards have one
# Only the SMT parts: the through-hole connectors (the XIAO sockets, the motor pads, the distance-sensor
# header, the BAT wires) are not fitted by JLC's economic assembly and ship loose in the kit.
_rows, _seen = {}, []
for ref, lib, val, fp, nets, at, dnp in D.PARTS:
    pj = D.JLC.get(ref)
    if not pj or not pj[1]:
        continue
    key = (val.split(" 0x")[0], fp.split(":")[-1], pj[1])
    if key not in _rows:
        _rows[key] = []
        _seen.append(key)
    _rows[key].append(ref)


def _refkey(r):
    import re as _re
    m = _re.match(r"([A-Za-z]+)(\d+)", r)
    return (m.group(1), int(m.group(2))) if m else (r, 0)


_csv = ["Comment,Designator,Footprint,LCSC Part #"]
for (val, fp, lcsc) in sorted(_seen, key=lambda k: (-len(_rows[k]), k[0])):
    refs = sorted(_rows[(val, fp, lcsc)], key=_refkey)
    des = ",".join(refs)
    _csv.append('%s,%s,%s,%s' % (f'"{val}"' if "," in val else val,
                                  f'"{des}"' if len(refs) > 1 else des, fp, lcsc))
_bom = f"{ROOTDIR}/../bom/{PRJ}-JLC-BOM.csv"
open(_bom, "w", encoding="utf-8", newline="\n").write("\n".join(_csv) + "\n")

